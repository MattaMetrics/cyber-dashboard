/** Resolve a complete library row by id */
export function getLibraryTrackById(id) {
  return staticAssessmentLibrary.find((track) => track.id === Number(id)) || null;
}

/** Tracks tagged for a package deck (e.g. VITAL_FLOW) */
export function getTracksByPackage(packageKey) {
  const key = String(packageKey || '').toUpperCase();
  return staticAssessmentLibrary.filter((track) =>
    (track.packages || []).some((p) => String(p).toUpperCase() === key)
  );
}

/** Resolve a library row by package deck + card slot (e.g. VITAL_FLOW, '1-1') */
export function getTrackByPackageSlot(packageKey, slot) {
  const key = String(packageKey || '');
  const slotKey = String(slot || '');
  return (
    staticAssessmentLibrary.find(
      (track) => track.packageSlots && track.packageSlots[key] === slotKey
    ) || null
  );
}

